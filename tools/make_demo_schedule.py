"""Генератор демо-расписания в том же формате Excel, что присылает вуз.

Нужен, чтобы прогнать импорт и панель на пустой БД, не имея реального файла:

    python tools/make_demo_schedule.py                 # → demo_schedule.xlsx
    python tools/make_demo_schedule.py out.xlsx

Формат повторяет то, что разбирает import_excel.py:
  * шапка на строке 8: «Пара», «Время», затем колонки «<Направление> \\n<N> курс»;
  * строки-разделители дня: колонка «Пара» пустая, в строке есть название дня;
  * строки пар: в колонке «Пара» номер, в «Время» — интервал;
  * маркеры чётности внутри ячейки: `*` — нечётная неделя, `**` — чётная.
"""

from __future__ import annotations

import sys

from openpyxl import Workbook

# Консоль Windows по умолчанию cp1251 и падает на кириллице в выводе.
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

HEADER_ROW = 8

# (направление, курс) — две группы в одной «Пара»-группе колонок
DIRECTIONS = [
    ("Информационные системы и технологии", 1),
    ("Прикладная математика и информатика", 2),
]

TIMES = [
    ("1", "8:00-9:30"),
    ("2", "9:40-11:10"),
    ("3", "11:20-12:50"),
    ("4", "13:20-14:50"),
]

DAYS = ["Понедельник", "Вторник", "Среда", "Четверг", "Пятница", "Суббота"]

# День → номер пары → ячейка для каждого направления.
# Специально включены: обычная пара, пара с чётностью (*/**), пара без аудитории,
# пустая ячейка — чтобы импорт проверялся на всех четырёх ветках парсера.
CELLS = {
    "Понедельник": {
        "1": ["Математический анализ, Иванов А. Б. лк 301",
              "Дискретная математика, Петрова В. Г. пр 214"],
        "2": ["Программирование, Сидоров Д. Е. лб 415",
              "Математический анализ, Иванов А. Б. лк 301"],
        "3": ["* Философия, Кузнецова Е. Ж. лк 108\n** Правоведение, Морозов З. И. лк 108",
              ""],
    },
    "Вторник": {
        "1": ["Базы данных, Волков К. Л. лк 302",
              "Теория вероятностей, Зайцева М. Н. лк 220"],
        "2": ["Базы данных, Волков К. Л. лб 417",
              "Теория вероятностей, Зайцева М. Н. пр 220"],
        "4": ["Физическая культура, Орлов О. П. пр",
              "Физическая культура, Орлов О. П. пр"],
    },
    "Среда": {
        "1": ["Операционные системы, Соколов Р. С. лк 303",
              "Численные методы, Лебедев Т. У. лк 221"],
        "2": ["Операционные системы, Соколов Р. С. лб 418",
              "Численные методы, Лебедев Т. У. лб 419"],
    },
    "Четверг": {
        "2": ["Английский язык, Новикова Ф. Х. пр 210",
              "Английский язык, Новикова Ф. Х. пр 211"],
        "3": ["Дискретная математика, Петрова В. Г. лк 304",
              "Функциональный анализ, Егоров Ц. Ч. лк 222"],
    },
    "Пятница": {
        "1": ["Web-разработка, Макаров Ш. Щ. лб 420",
              "Алгебра, Виноградов Э. Ю. лк 223"],
        "2": ["** Web-разработка, Макаров Ш. Щ. лб 420",
              "Алгебра, Виноградов Э. Ю. пр 223"],
    },
    "Суббота": {
        "1": ["История, Тарасов Я. А. лк 105", ""],
    },
}


def build(path: str) -> str:
    wb = Workbook()
    ws = wb.active
    ws.title = "Расписание"

    ws.cell(1, 1).value = "ДЕМО-РАСПИСАНИЕ (сгенерировано tools/make_demo_schedule.py)"
    ws.cell(2, 1).value = "Формат совпадает с реальным файлом вуза"

    # Шапка: Пара | Время | направление1 | направление2
    ws.cell(HEADER_ROW, 1).value = "Пара"
    ws.cell(HEADER_ROW, 2).value = "Время"
    for offset, (direction, course) in enumerate(DIRECTIONS):
        ws.cell(HEADER_ROW, 3 + offset).value = f"{direction} \n{course} курс"

    row = HEADER_ROW + 1
    for day in DAYS:
        # Строка-разделитель дня: колонка «Пара» пуста, день лежит в соседней.
        ws.cell(row, 2).value = day
        row += 1
        for para, time_str in TIMES:
            day_cells = CELLS.get(day, {}).get(para)
            if not day_cells:
                continue
            ws.cell(row, 1).value = int(para)
            ws.cell(row, 2).value = time_str
            for offset, text in enumerate(day_cells):
                if text:
                    ws.cell(row, 3 + offset).value = text
            row += 1

    wb.save(path)
    return path


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "demo_schedule.xlsx"
    print("Записан демо-файл:", build(out))
